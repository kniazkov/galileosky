/**
 * @file power.hpp
 * @brief Задаёт платформенную границу управления питанием внешних модулей.
 *
 * Общая логика выбирает только домен питания и требуемое состояние. Конкретный
 * GPIO, внешний ключ и электрическая полярность остаются в реализации платформы.
 */

#pragma once

#include <cstdint>

namespace drivers::power {

/**
 * @brief Перечисляет независимо управляемые домены питания.
 */
enum class Domain : std::uint8_t {
    gnss
};

/**
 * @brief Возвращает платформенный драйвер в исходное состояние.
 */
void reset();

/**
 * @brief Задаёт требуемое состояние выбранного домена питания.
 */
void set_enabled(Domain domain, bool enabled);

}  // пространство имён drivers::power
